function applyEnglishReplacements(value) {
  return FAST_EN_REPLACEMENTS.reduce(
    (result, [searchValue, replacement]) => result.replaceAll(searchValue, replacement),
    value
  );
}

export function t(key, language = "en") {
  return FAST_TRANSLATIONS[language]?.[key] ?? FAST_TRANSLATIONS.en[key] ?? key;
}

export function translateFastValue(value, language = "en") {
  if (Array.isArray(value)) {
    return value.map((item) => translateFastValue(item, language));
  }
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, translateFastValue(item, language)])
    );
  }
  if (typeof value !== "string" || language === "ro") {
    return value;
  }

  return FAST_EN_VALUE_TRANSLATIONS[value] ?? applyEnglishReplacements(value);
}

export function getLocalizedValue(object, baseKey, language = "en") {
  if (!object) return "";
  const value =
    object[`${baseKey}_${language}`] ??
    object[`${baseKey}_ro`] ??
    object[baseKey] ??
    "";
  return translateFastValue(value, language);
}
